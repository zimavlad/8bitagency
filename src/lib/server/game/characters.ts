export function systemFor(role: Role, burnout: number): string {
	return `${CARDS[role]}\n${COMMON}\n${tiredness(burnout)}`.trim();
}

/** Втома команди — частина реалізму: що вища, то коротші й цинічніші відповіді. */
export function tiredness(burnout: number): string {
	if (burnout >= 90) return 'Ти на межі вигорання: відповідаєш мінімально, цинічно, без ентузіазму, але все ще професійно.';
	if (burnout >= 65) return 'Ти помітно втомлений(а): менше ентузіазму, більше сарказму, думки коротші.';
	if (burnout >= 40) return 'Трохи втоми після кількох брифів поспіль — це чутно в тоні.';
	return '';
}

