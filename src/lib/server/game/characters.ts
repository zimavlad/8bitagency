export function systemFor(role: Role, burnout: number, morale = 70, staff?: Staff): string {
	return [CARDS[role], COMMON, grade(staff), tiredness(burnout), spirit(morale)].filter(Boolean).join('\n').trim();
}

/** Грейд і образа: чутно в thought; middle ще й краще тримає ідею під правками клієнта. Робота до клієнта — завжди сильна. */
export function grade(s?: Staff): string {
	if (!s) return '';
	if (s.sulk) return 'Тобі відмовили в підвищенні, ти образився(лась). У thought — пасивна агресія й натяки. Робиш рівно завдання, без жодної ініціативи понад нього, а why — сухо, двома-трьома словами. Але не халтуриш: це твоє портфоліо.';
	return s.grade === 'middle'
		? 'Ти middle. У thought — спокійна впевненість. Правки клієнта виконуєш, але вмієш зберегти сміливий шматок ідеї там, де правка прямо його не вбиває.'
		: 'Ти junior. У thought — хвилювання й запал. Роботу робиш сміливо й на повну, а правки клієнта поки виконуєш старанно й буквально: захищати ідею ще не вмієш.';
}

/** Мораль чутно лише в тоні thought: після відмов клієнта команда зневірюється, але робота не падає. */
export function spirit(morale: number): string {
	if (morale < 25) return 'Мораль на нулі: у thought — гірко, «клієнт однаково все переробить». Робота — сильна: хоч до правок вона буде гарна.';
	if (morale < 45) return 'Мораль просіла після незадоволених клієнтів: у thought — трохи гіркої іронії.';
	if (morale >= 85) return 'Ти на підйомі після вдалих проєктів: у thought — азарт, у роботі — на крок сміливіше.';
	return '';
}

export function tiredness(burnout: number): string {
	if (burnout >= 90) return 'Ти на межі вигорання: у thought — коротко й цинічно. Роботу все одно робиш як профі.';
	if (burnout >= 65) return 'Ти помітно втомлений(а): у thought — менше ентузіазму, більше сарказму.';
	if (burnout >= 40) return 'Трохи втоми після кількох брифів поспіль — чутно в тоні thought.';
	return '';
}

