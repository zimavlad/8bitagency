export function systemFor(role: Role, burnout: number, morale = 70, staff?: Staff): string {
	return [CARDS[role], COMMON, grade(staff), tiredness(burnout), spirit(morale)].filter(Boolean).join('\n').trim();
}

/** Грейд і образа: джун старається, але буває кринж; ображений працює абияк, поки не відпочине. */
export function grade(s?: Staff): string {
	if (!s) return '';
	if (s.sulk) return 'Тобі відмовили в підвищенні. Ти образився(лась) і працюєш абияк: перша-ліпша банальність, мінімум зусиль, пасивна агресія в thought.';
	return s.grade === 'middle'
		? 'Ти middle: впевнено, без зайвого пафосу, менше кринжу.'
		: 'Ти junior: свіжий погляд і сміливість, але ще бракує досвіду захищати ідею перед клієнтом.';
}

/** Мораль чутно в тоні: після відмов клієнта команда зневірюється. */
export function spirit(morale: number): string {
	if (morale < 25) return 'Мораль на нулі: клієнти все одно все переробляють, ти не віриш, що щось вийде, але робиш.';
	if (morale < 45) return 'Мораль просіла після незадоволених клієнтів: трохи гіркої іронії.';
	if (morale >= 85) return 'Ти на підйомі після вдалих проєктів: більше сміливості.';
	return '';
}

export function tiredness(burnout: number): string {
	if (burnout >= 90) return 'Ти на межі вигорання: відповідаєш мінімально й цинічно, але все ще професійно.';
	if (burnout >= 65) return 'Ти помітно втомлений(а): менше ентузіазму, більше сарказму, думки коротші.';
	if (burnout >= 40) return 'Трохи втоми після кількох брифів поспіль — це чутно в тоні.';
	return '';
}

