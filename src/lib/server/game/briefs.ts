/** Детермінований вибір за зерном: однаковий день дає однакові брифи. */
function rng(seed: number): () => number {
	let s = seed >>> 0;
	return () => {
		s = (s + 0x6d2b79f5) >>> 0;
		let t = s;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}

/** Старі сейви не знали, що брали: відновлюємо за назвою бізнесу з історії. */
export function takenFrom(businesses: string[]): string[] {
	return POOL.flatMap((b, i) => (businesses.includes(b.client.business) ? [`b${i}`] : []));
}

export const prepayOf = (fee: number) => Math.round((fee * PREPAY_SHARE) / 100) * 100;
export const CUSTOM_FEE: Record<number, number> = { 1: 4000, 2: 15000, 3: 45000 };

/** Три вхідні брифи на день за рівнем агенції; якщо свого рівня мало — додаємо з попереднього. */
export function inboxFor(day: number, reputation: number, exclude: string[] = []): Brief[] {
	const r = rng(day * 7919 + 13);
	const tier = tierOf(reputation);
	const every = POOL.map((b, i) => ({ ...b, i }));
	const picked: typeof every = [];
	const take = (list: typeof every) => {
		const open = list.filter((b) => !picked.includes(b));
		while (picked.length < 3 && open.length) picked.push(open.splice(Math.floor(r() * open.length), 1)[0]);
	};
	// Спершу нові брифи свого рівня, потім нові нижчих; коли нові скінчились — повтори свого рівня.
	const fresh = every.filter((b) => !exclude.includes(`b${b.i}`));
	for (const t of [tier, tier - 1, tier - 2]) take(fresh.filter((b) => b.tier === t));
	take(every.filter((b) => b.tier === tier));
	take(every.filter((b) => b.tier < tier));
	return picked.map((b) => ({ id: `b${b.i}`, client: b.client, text: b.text, fee: b.fee, prepay: prepayOf(b.fee), tier: b.tier, ...(b.budget ? { budget: b.budget } : {}) }));
}

const CUSTOM_ARCHETYPES = [
	'хоче як у конкурента, тільки дешевше; на все питає «а продавати буде?»',
	'любить великий логотип, знижки й номер телефону в кожному креативі',
	'постійно радиться з кумом, який «шарить у маркетингу»'
];

/** Текст брифу з полів форми: так само сиро, як пишуть клієнти, але з усіма блоками. */
export function briefText(f: BriefForm): string {
	const part = (label: string, v: string) => (v.trim() ? `${label}: ${v.trim()}` : '');
	return [part('Бізнес', f.business), part('Цілі', f.goals), part('Побажання', f.wishes), part('Конкуренти', f.competitors), part('УТП', f.usp)].filter(Boolean).join('\n');
}

/** Свій бриф; клієнта-персонажа потім уточнює модель (персона під бізнес). */
export function customBrief(f: BriefForm, day: number, reputation = 0): Brief {
	const text = briefText(f);
	const r = rng(day * 31 + text.length);
	return {
		id: `c${day}-${text.length}`,
		client: {
			name: 'Замовник',
			business: f.business.trim().split(/[.,;\n]/)[0].slice(0, 80) || 'ваш бізнес',
			archetype: CUSTOM_ARCHETYPES[Math.floor(r() * CUSTOM_ARCHETYPES.length)],
			gender: r() > 0.5 ? 'f' : 'm',
			look: (['leather', 'suit', 'casual', 'creative', 'farmer', 'sport'] as const)[Math.floor(r() * 6)]
		},
		text,
		fee: CUSTOM_FEE[tierOf(reputation)],
		prepay: prepayOf(CUSTOM_FEE[tierOf(reputation)]),
		tier: tierOf(reputation),
		custom: true
	};
}
