export function customBrief(text: string, business: string, day: number): Brief {
	const r = rng(day * 31 + text.length);
	return {
		id: `c${day}-${text.length}`,
		client: { name: 'Замовник', business: business.trim() || 'ваш бізнес', archetype: CUSTOM_ARCHETYPES[Math.floor(r() * CUSTOM_ARCHETYPES.length)] },
		text: text.trim(),
		fee: 20000,
		custom: true
	};
}
