/** Детермінований вибір за зерном: однаковий день дає однакові брифи. */
function rng(seed: number): () => number {
	let s = seed >>> 0;
	return () => {
		s = (s + 0x6d2b79f5) >>> 0;
		let t = s;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}

/** Три вхідні брифи на день. Що вища репутація — то більше дорогих клієнтів і трохи вищі гонорари. */
export function inboxFor(day: number, reputation: number, exclude: string[] = []): Brief[] {
	const r = rng(day * 7919 + 13);
	const open = POOL.map((b, i) => ({ ...b, i })).filter((b) => (b.minRep ?? 0) <= reputation && !exclude.includes(`b${b.i}`));
	const picked: typeof open = [];
	while (picked.length < 3 && open.length) picked.push(open.splice(Math.floor(r() * open.length), 1)[0]);
	const bonus = 1 + Math.max(0, reputation - 50) / 100;
	return picked.map((b) => ({
		id: `b${b.i}`,
		client: b.client,
		text: b.text,
		fee: Math.round((b.fee * bonus) / 500) * 500
	}));
}

